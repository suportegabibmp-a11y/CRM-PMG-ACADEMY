-- Criar view para subscriptions ativas
CREATE OR REPLACE VIEW active_subscriptions AS
SELECT 
  id,
  email,
  customer_id,
  plan,
  status,
  amount,
  currency,
  interval,
  created_at,
  expires_at
FROM subscriptions 
WHERE status = 'active';

-- Criar função para verificar se usuário é premium
CREATE OR REPLACE FUNCTION is_premium(user_email TEXT)
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM subscriptions 
    WHERE email = user_email 
    AND status = 'active' 
    AND (expires_at IS NULL OR expires_at > NOW())
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Criar função para obtier tier do usuário
CREATE OR REPLACE FUNCTION get_user_tier(user_email TEXT)
RETURNS TEXT AS $$
BEGIN
  RETURN COALESCE(
    (
      SELECT plan FROM subscriptions 
      WHERE email = user_email 
      AND status = 'active' 
      AND (expires_at IS NULL OR expires_at > NOW())
      LIMIT 1
    ), 
    'free'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

