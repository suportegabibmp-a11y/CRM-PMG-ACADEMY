-- Tabela de Subscriptions para integração com Cakto
-- Esta tabela armazena informações sobre assinaturas e pagamentos

-- Criar tabela de subscriptions
CREATE TABLE IF NOT EXISTS subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  customer_id VARCHAR(255) NOT NULL,
  plan VARCHAR(50) NOT NULL DEFAULT 'premium',
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  subscription_id VARCHAR(255),
  purchase_id VARCHAR(255),
  amount DECIMAL(10,2),
  currency VARCHAR(3) DEFAULT 'BRL',
  payment_method VARCHAR(50),
  interval VARCHAR(20) DEFAULT 'monthly',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  cancelled_at TIMESTAMP WITH TIME ZONE,
  expires_at TIMESTAMP WITH TIME ZONE
);

-- Criar índices para performance
CREATE INDEX IF NOT EXISTS idx_subscriptions_email ON subscriptions(email);
CREATE INDEX IF NOT EXISTS idx_subscriptions_customer_id ON subscriptions(customer_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_status ON subscriptions(status);
CREATE INDEX IF NOT EXISTS idx_subscriptions_subscription_id ON subscriptions(subscription_id);

-- Adicionar coluna subscription_tier na tabela profiles se não existir
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_name = 'profiles' AND column_name = 'subscription_tier'
  ) THEN
    ALTER TABLE profiles ADD COLUMN subscription_tier VARCHAR(20) DEFAULT 'free';
  END IF;
END $$;

-- Atualizar timestamp automaticamente
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ language 'plpgsql';

-- Criar trigger para atualizar updated_at
CREATE TRIGGER update_subscriptions_updated_at 
  BEFORE UPDATE ON subscriptions 
  FOR EACH ROW 
  EXECUTE FUNCTION update_updated_at_column();

-- Política de segurança (RLS) - permitir inserções via webhook
ALTER TABLE subscriptions ENABLE ROW LEVEL SECURITY;

-- Política para permitir inserções (webhook do Cakto)
CREATE POLICY "Allow webhook insertions" ON subscriptions
  FOR INSERT WITH CHECK (true);

-- Política para permitir atualizações (webhook do Cakto)
CREATE POLICY "Allow webhook updates" ON subscriptions
  FOR UPDATE USING (true);

-- Política para permitir leituras para usuários autenticados
CREATE POLICY "Allow authenticated reads" ON subscriptions
  FOR SELECT USING (auth.role() = 'authenticated');

-- Política para permitir que usuários vejam suas próprias subscriptions
CREATE POLICY "Allow users to see own subscriptions" ON subscriptions
  FOR SELECT USING (auth.email() = email);

